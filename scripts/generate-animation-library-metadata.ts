import { writeFile } from "node:fs/promises";
import { kpLogExponentAnimationId } from "../src/animation/log-exponent-adapter.ts";
import { kpLogarithmChangeOfBaseExemplarId } from "../src/animation/logarithm-change-of-base-exemplar.ts";
import { createKpAnimationAssets } from "../src/animation/catalog.ts";
import {
  createSymbolicManipulationFamilyRegistry
} from "../src/animation/symbolic-manipulation-family-registry.ts";
import {
  projectKpAnimationAssetsToEditorDescriptors
} from "../src/editor/animation-catalog-projection.ts";

const descriptors = projectKpAnimationAssetsToEditorDescriptors({
  assets: createKpAnimationAssets(),
  families: createSymbolicManipulationFamilyRegistry()
});
const output = `${JSON.stringify(descriptors, null, 2)}\n`;

await writeFile(
  new URL("../src/editor/animation-library-metadata.generated.json", import.meta.url),
  output,
  "utf8"
);

console.log(`generated ${descriptors.length} animation library descriptors`);

// Prepared standalone cards need one exact descriptor, not the picker catalogue.
// Both projections are generated by the same owner and checked against it.
for (const [animationId, path] of [
  [kpLogExponentAnimationId, "../src/tutorial/kinetic-figure-log-exponent-focus-card/descriptor.generated.ts"],
  [kpLogarithmChangeOfBaseExemplarId, "../src/experiments/authoring-market/equation-descriptor.generated.ts"]
] as const) {
  const descriptor = descriptors.find(item => item.animationId === animationId);
  if (!descriptor) throw new Error(`Missing prepared descriptor: ${animationId}`);
  const module = '// Generated by scripts/generate-animation-library-metadata.ts.\n'
    + 'import type { KpEditorAnimationDescriptor } from "../../editor/animation-descriptor.ts";\n'
    + `const descriptor: KpEditorAnimationDescriptor = ${JSON.stringify(descriptor, null, 2)};\nexport default descriptor;\n`;
  await writeFile(new URL(path, import.meta.url), module, "utf8");
}
